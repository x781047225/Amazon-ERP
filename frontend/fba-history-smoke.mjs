import {chromium} from '@playwright/test';
const root=new URL('../',import.meta.url).pathname;
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1000},locale:'zh-CN'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8787');
await page.locator('button.nav-item').filter({hasText:'FBA 货件'}).click();
await page.getByPlaceholder('搜索 FBA 号 / 名称 / SKU / FNSKU').fill('FBATEST00004');
await page.getByRole('button',{name:'查询',exact:true}).click();
await page.getByRole('button',{name:'FBATEST00004',exact:true}).click();
await page.locator('.el-drawer .el-table__row').first().waitFor();
await page.screenshot({path:root+'docs/fba-demostoreb-detail.png',fullPage:true});
await page.getByRole('button',{name:'当时明细',exact:true}).first().click();
await page.getByText('历史商品明细',{exact:true}).waitFor();
await page.locator('.el-dialog').filter({hasText:'历史商品明细'}).locator('.el-table__row').first().waitFor();
await page.waitForTimeout(600);
console.log('Dialog geometry',await page.locator('.el-dialog').filter({hasText:'历史商品明细'}).evaluate(el=>({rect:el.getBoundingClientRect().toJSON(),parent:el.parentElement?.outerHTML.slice(0,250),count:el.querySelectorAll('.el-table__row').length,overlays:[...document.querySelectorAll('.el-overlay')].map(x=>({z:getComputedStyle(x).zIndex,display:getComputedStyle(x).display,child:x.textContent?.slice(0,60)}))})));
await page.screenshot({path:root+'docs/fba-snapshot.png',fullPage:true});
console.log(JSON.stringify({pageErrors:errors,checks:['known DemoStoreB shipment details','saved snapshot item rows']}));
await browser.close();if(errors.length)process.exit(1);
